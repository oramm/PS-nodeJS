/**
 * AGD-1 — tabela tras PS dla agenta pracownika: odczyt, zapis albo zamknięte, z powodem po ludzku.
 *
 * Klasa jest z odczytu obsługi trasy, nie z metody: wyszukiwarki to POST, a GET /autoApproveOurLetters
 * zatwierdza wszystkie pisma (plan AGD, decyzja K1 z 2026-11-19, tabela z notatki AGD-0).
 * Trasa bez wpisu jest dla agenta zamknięta, a test kompletności nie pozwala jej wydać bez wpisu.
 */

export type AgentRouteAccess = 'odczyt' | 'zapis' | 'zamkniete';
/** Poziom "baza PS" z Dostępów SB, z którym agent osoby wszedł do PS. */
export type PersonAgentPsDb = 'ro' | 'rw';

/** Do kogo agent odsyła osobę po uprawnienie (decyzja właściciela 2026-11-19: "na razie do mnie"). */
export const AGENT_ADMINISTRATOR = 'Marek Gazda';

export function agentRefusal(reason: string): string {
    return (
        `Agent nie może tego zrobić: ${reason}. Jeśli uważasz, że powinieneś mieć to uprawnienie, ` +
        `bo bez niego nie wykonasz swojej pracy, zgłoś się do administratora: ${AGENT_ADMINISTRATOR}.`
    );
}

const READ_ONLY_REASON = 'agent tej osoby ma w PS tylko odczyt (Dostępy SB: "baza PS: odczyt")';
const UNDESCRIBED_ROUTE_REASON = 'tej trasy nie opisano dla agenta';

// Ten sam kompilator wzorców co routing Expressu 4 (jego zależność), więc dopasowanie jest identyczne.
const pathToRegexp: (path: string, keys: unknown[], options: object) => RegExp = require('path-to-regexp');

const RANK: Record<AgentRouteAccess, number> = { odczyt: 0, zapis: 1, zamkniete: 2 };

function isAllowedAccess(access: AgentRouteAccess, level: PersonAgentPsDb): boolean {
    return access === 'odczyt' || (access === 'zapis' && level === 'rw');
}

/** Tabela dla agenta osoby z danym poziomem: AGD-2 liczy z niej ekran, envi-ps czyta ją przez GET /agentRoutes. */
export function agentRoutesFor(level: PersonAgentPsDb) {
    return AGENT_ROUTE_TABLE.map(([method, path, access, reason]) => ({
        method,
        path,
        access,
        reason,
        allowed: isAllowedAccess(access, level),
    }));
}

type CompiledRoute = { method: string; access: AgentRouteAccess; reason: string; regExp: RegExp };
let compiled: CompiledRoute[] | undefined;

/** Wpis dla żądania. Gdy pasuje kilka wzorców, wygrywa najostrzejszy - nie zależymy od kolejności rejestracji tras. */
export function findAgentRoute(method: string, path: string) {
    compiled ??= AGENT_ROUTE_TABLE.map(([m, p, access, reason]) => ({
        method: m,
        access,
        reason,
        regExp: pathToRegexp(p, [], { sensitive: false, strict: false, end: true }),
    }));
    // Express obsługuje HEAD trasą GET.
    const upper = method.toUpperCase() === 'HEAD' ? 'GET' : method.toUpperCase();
    let found: CompiledRoute | undefined;
    for (const route of compiled) {
        if (route.method !== upper || !route.regExp.test(path)) continue;
        if (!found || RANK[route.access] > RANK[found.access]) found = route;
    }
    return found;
}

/** Powód odmowy dla agenta osoby albo undefined, gdy wolno. */
export function agentRefusalReason(level: PersonAgentPsDb, method: string, path: string): string | undefined {
    const route = findAgentRoute(method, path);
    if (!route) return UNDESCRIBED_ROUTE_REASON;
    if (route.access === 'zamkniete') return route.reason.charAt(0).toLowerCase() + route.reason.slice(1).replace(/\.$/, '');
    if (!isAllowedAccess(route.access, level)) return READ_ONLY_REASON;
    return undefined;
}

